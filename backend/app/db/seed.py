def _document_values(doc_type: DocTypeKey, company: dict[str, str], person: dict[str, str]):
    """Return (field values, pdf lines) for one document."""
    if doc_type == DocTypeKey.trade_license:
        expiry = _date(rng.choice([-30, 60, 120, 240, 400]))
        values = {
            "license_number": _licence_number(),
            "company_name_en": company["en"],
            "company_name_ar": company["ar"],
            "legal_form": rng.choice(LEGAL_FORMS),
            "licensing_authority": rng.choice(LICENSING_AUTHORITIES),
            "business_activity": company["activity"],
            "issue_date": _date(-rng.randint(400, 1200)),
            "expiry_date": expiry,
            "registered_address": f"Office {rng.randint(100, 2400)}, Business Tower (synthetic)",
        }
    elif doc_type == DocTypeKey.emirates_id:
        values = {
            "id_number": _emirates_id(),
            "full_name_en": person["en"],
            "full_name_ar": person["ar"],
            "nationality": person["nationality"],
            "date_of_birth": _date(-rng.randint(8000, 18000)),
            "expiry_date": _date(rng.choice([-15, 90, 300, 700])),
            "card_number": str(rng.randint(100000000, 999999999)),
        }
    elif doc_type == DocTypeKey.passport:
        values = {
            "passport_number": _passport_number(),
            "full_name": person["en"],
            "nationality": person["nationality"],
            "date_of_birth": _date(-rng.randint(8000, 18000)),
            "issue_date": _date(-rng.randint(400, 2500)),
            "expiry_date": _date(rng.choice([100, 400, 900, 1600])),
        }
    elif doc_type == DocTypeKey.moa:
        values = {
            "company_name_en": company["en"],
            "share_capital": f"AED {rng.choice([150, 300, 500, 1000, 2500]) * 1000:,}",
            "shareholders": f"{person['en']} (60%), {rng.choice(PEOPLE)['en']} (40%)",
            "incorporation_date": _date(-rng.randint(600, 3000)),
            "notary_reference": f"NOT-{rng.randint(10000, 99999)}",
        }
    else:  # salary certificate
        basic = rng.choice([12000, 18000, 22000, 30000, 45000])
        values = {
            "employee_name": person["en"],
            "employer_name": company["en"],
            "designation": rng.choice(
                ["Operations Manager", "Senior Engineer", "Finance Lead", "Account Manager"]
            ),
            "basic_salary": f"AED {basic:,}",
            "total_salary": f"AED {int(basic * rng.uniform(1.2, 1.6)):,}",
            "issue_date": _date(-rng.randint(5, 120)),
            "iban": _iban(),
        }
    lines = [(key.replace("_", " "), str(value)) for key, value in values.items()]
    return values, lines


async def seed_cases(
    db: AsyncSession,
    users: dict[Role, models.User],
    doc_types: dict[DocTypeKey, models.DocumentType],
) -> None:
    storage = get_storage()
    ops = users[Role.ops_officer]
    reviewer = users[Role.reviewer]
    supervisor = users[Role.supervisor]

    schema_by_key = {
        definition["key"]: {f["name"]: f for f in definition["fields"]}  # type: ignore[index]
        for definition in DOC_TYPE_DEFS
    }

    statuses: list[CaseStatus] = []
    for status, count in STATUS_PLAN:
        statuses.extend([status] * count)

    year = datetime.now(UTC).year
    for index, status in enumerate(statuses, start=1):
        company = COMPANIES[index % len(COMPANIES)]
        person = PEOPLE[index % len(PEOPLE)]
        # Half a day for the newest cases, up to 14 days for the oldest.
        age_hours = int(rng.triangular(1, 14 * 24, 40)) if index > 3 else rng.randint(1, 8)
        created_at = datetime.now(UTC) - timedelta(hours=age_hours)

        is_salary = index % 10 == 0
        case_type = CaseType.salary_certificate if is_salary else CaseType.kyc_refresh
        needs_human = status in (
            CaseStatus.needs_review,
            CaseStatus.in_review,
            CaseStatus.rejected,
        )
        reviewed_and_done = status in (CaseStatus.completed, CaseStatus.approved) and index % 3 == 0
        straight_through = status in (CaseStatus.completed, CaseStatus.approved) and not (
            reviewed_and_done
        )
        confident = not (needs_human or reviewed_and_done)

        case = models.Case(
            reference=f"WTQ-{year}-{index:04d}",
            case_type=case_type,
            customer_name=company["en"],
            customer_name_ar=company["ar"],
            status=status,
            risk_level=(
                RiskLevel.high
                if status in (CaseStatus.rejected, CaseStatus.failed)
                else RiskLevel.medium
                if needs_human
                else RiskLevel.low
            ),
            priority=rng.choice([Priority.normal, Priority.normal, Priority.high, Priority.urgent]),
            notes="",
            thread_id=f"wf_{rng.getrandbits(48):012x}",
            confidence=None
            if status in (CaseStatus.intake, CaseStatus.processing)
            else round(rng.uniform(0.93, 0.99) if confident else rng.uniform(0.61, 0.88), 3),
            straight_through=straight_through,
            processing_ms=None
            if status in (CaseStatus.intake, CaseStatus.processing)
            else rng.randint(18000, 95000),
            cost_usd=None
            if status in (CaseStatus.intake, CaseStatus.processing)
            else round(rng.uniform(0.011, 0.074), 4),
            created_by_id=ops.id,
            assigned_to_id=(
                reviewer.id
                if status == CaseStatus.in_review
                else supervisor.id
                if status == CaseStatus.failed
                else None
            ),
            sla_due_at=created_at + timedelta(hours=settings.review_sla_hours),
            completed_at=(
                created_at + timedelta(minutes=rng.randint(12, 240))
                if status in (CaseStatus.completed, CaseStatus.rejected)
                else None
            ),
            created_at=created_at,
            updated_at=created_at + timedelta(minutes=rng.randint(5, 300)),
        )
        db.add(case)
        await db.flush()

        # --- documents + fields
        doc_keys = (
            [DocTypeKey.salary_certificate]
            if is_salary
            else [DocTypeKey.trade_license, DocTypeKey.emirates_id, DocTypeKey.passport]
            + ([DocTypeKey.moa] if index % 2 == 0 else [])
        )
        order = 0
        for doc_key in doc_keys:
            values, lines = _document_values(doc_key, company, person)
            label = DOC_TYPE_LABELS[doc_key]
            pdf = simple_pdf(f"{label} (synthetic)", lines, FOOTER)
            filename = f"{doc_key.value}_{case.reference}.pdf"
            path = storage.save(case.id, filename, pdf)

            document = models.Document(
                case_id=case.id,
                filename=filename,
                doc_type=doc_key,
                language=Language.mixed if doc_key == DocTypeKey.trade_license else Language.en,
                mime_type="application/pdf",
                size_bytes=len(pdf),
                page_count=1,
                storage_path=path,
                ocr_confidence=round(rng.uniform(0.88, 0.995), 3),
                classification_confidence=round(rng.uniform(0.9, 0.999), 3),
                status=(
                    DocumentStatus.uploaded
                    if status == CaseStatus.intake
                    else DocumentStatus.extracted
                ),
                created_at=created_at + timedelta(seconds=rng.randint(5, 60)),
            )
            db.add(document)
            await db.flush()

            if status == CaseStatus.intake:
                continue

            schema = schema_by_key[doc_key]
            for field_name, value in values.items():
                meta: dict[str, Any] = schema.get(field_name, {})
                critical = bool(meta.get("is_critical"))
                # A doubtful case has one weak critical field — that is what triggers review.
                high = confident or not critical or rng.random() > 0.6
                raw = _confidence(high)
                # A reviewer looked at this case and sometimes changed a value. Those
                # corrections are the ground truth the confidence curve is fitted on
                # (services/assurance.py), so the demo needs some — and they have to be
                # realistic: a low score is corrected far more often than a high one.
                corrected = reviewed_and_done and rng.random() < (0.45 if raw < 0.85 else 0.04)
                db.add(
                    models.ExtractedField(
                        case_id=case.id,
                        document_id=document.id,
                        name=field_name,
                        label_en=meta.get("label_en", field_name.replace("_", " ").title()),
                        label_ar=meta.get("label_ar", ""),
                        value=str(value),
                        corrected_value=f"{value} (corrected)" if corrected else None,
                        confidence=raw,
                        calibrated_confidence=_calibrate(raw),
                        status=(
                            FieldStatus.corrected
                            if corrected
                            else FieldStatus.auto_accepted
                            if raw >= 0.9
                            else FieldStatus.needs_review
                        ),
                        is_critical=critical,
                        page=1,
                        bbox=[
                            round(rng.uniform(0.08, 0.15), 3),
                            round(0.12 + order * 0.055, 3),
                            round(rng.uniform(0.35, 0.6), 3),
                            0.035,
                        ],
                        source_text=f"{field_name.replace('_', ' ')}: {value}",
                        order_index=order,
                        created_at=document.created_at,
                    )
                )
                order += 1

        # --- findings
        findings_for_case: list[dict[str, Any]] = []
        if needs_human or status == CaseStatus.failed:
            findings_for_case.append(FINDING_TEMPLATES[index % len(FINDING_TEMPLATES)])
        if reviewed_and_done or index % 7 == 0:
            findings_for_case.append(FINDING_TEMPLATES[(index + 3) % len(FINDING_TEMPLATES)])

        resolved = status in (CaseStatus.completed, CaseStatus.approved)
        for template in findings_for_case:
            db.add(
                models.Finding(
                    case_id=case.id,
                    code=template["code"],
                    severity=template["severity"],
                    title=template["title"],
                    description=template["description"],
                    policy_citation=template["policy_citation"],
                    policy_quote=template["policy_quote"],
                    status=FindingStatus.resolved if resolved else FindingStatus.open,
                    created_at=created_at + timedelta(minutes=2),
                )
            )

        # --- review task
        if needs_human or reviewed_and_done:
            default_reason = "LOW_CONFIDENCE_CRITICAL_FIELD"
            reason_code = findings_for_case[0]["code"] if findings_for_case else default_reason
            mandatory = reason_code in (
                "SANCTIONS_POSSIBLE_MATCH",
                "DOCUMENT_EXPIRED",
                "SUSPECTED_INJECTION",
            )
            task_status = (
                ReviewStatus.pending
                if status == CaseStatus.needs_review
                else ReviewStatus.in_progress
                if status == CaseStatus.in_review
                else ReviewStatus.completed
            )
            decision = None
            if task_status == ReviewStatus.completed:
                decision = (
                    ReviewDecision.reject
                    if status == CaseStatus.rejected
                    else rng.choice([ReviewDecision.approve, ReviewDecision.correct])
                )
            db.add(
                models.ReviewTask(
                    case_id=case.id,
                    reason=ReviewReason.mandatory if mandatory else ReviewReason.dynamic,
                    reason_code=reason_code,
                    reason_label=REVIEW_REASON_LABELS.get(reason_code, "Needs human review"),
                    status=task_status,
                    assigned_role=Role.reviewer,
                    assigned_to_id=(
                        reviewer.id if task_status != ReviewStatus.pending else None
                    ),
                    sla_due_at=created_at + timedelta(hours=settings.review_sla_hours),
                    decision=decision,
                    decision_reason_code=(
                        "VALUES_CONFIRMED"
                        if decision == ReviewDecision.approve
                        else "OCR_ERROR"
                        if decision == ReviewDecision.correct
                        else "ILLEGIBLE_DOCUMENT"
                        if decision
                        else None
                    ),
                    decision_note=None,
                    completed_at=(
                        created_at + timedelta(minutes=rng.randint(20, 180)) if decision else None
                    ),
                    created_at=created_at + timedelta(minutes=3),
                )
            )

        # --- timeline / audit events
        await _seed_events(
            db,
            case=case,
            status=status,
            documents=len(doc_keys),
            ops=ops,
            reviewer=reviewer,
            findings=findings_for_case,
            created_at=created_at,
        )

    await db.flush()
    logger.info("seeded %d cases", len(statuses))


async def _seed_events(
    db: AsyncSession,
    *,
    case: models.Case,
    status: CaseStatus,
    documents: int,
    ops: models.User,
    reviewer: models.User,
    findings: list[dict[str, Any]],
    created_at: datetime,
) -> None:
    steps: list[tuple[int, str, str, str, ActorType, str | None, int | None]] = [
        (0, "case.created", f"Case {case.reference} created for {case.customer_name}",
         ops.full_name, ActorType.user, None, None),
        (20, "documents.uploaded", f"{documents} document(s) uploaded",
         ops.full_name, ActorType.user, None, None),
    ]
    if status != CaseStatus.intake:
        steps += [
            (45, "pipeline.started", "Conductor workflow started", "conductor",
             ActorType.system, None, None),
            (50, "guardrails.checked",
             "Prompt shield and PII tokenisation passed", "guardrails",
             ActorType.system, None, 220),
            (60, "documents.classified",
             f"{documents} document(s) classified", "supervisor_node",
             ActorType.agent, "classify_document@1.1.0", 1400),
            (95, "fields.extracted",
             "Fields extracted with per-field confidence", "worker_extract",
             ActorType.agent, "extract_trade_license@2.1.0", 5200),
            (140, "critic.reviewed", "Critic challenged the doubtful fields", "critic_node",
             ActorType.agent, "critic_challenge@1.0.0", 2100),
            (170, "rules.validated", "Cross-field rules applied (rules v1.1.0)", "validator_node",
             ActorType.agent, None, 180),
            (180, "confidence.calibrated", "Confidence calibrated on the golden set",
             "calibrator", ActorType.system, None, 40),
        ]
    for template in findings:
        steps.append(
            (200, "finding.raised", f"Finding raised: {template['title']}", "validator_node",
             ActorType.agent, None, None)
        )

    if status in (CaseStatus.needs_review, CaseStatus.in_review):
        steps.append(
            (210, "review.required", "Review gate paused the graph for a human",
             "review_gate", ActorType.agent, None, None)
        )
    if status == CaseStatus.in_review:
        steps.append(
            (900, "review.claimed", f"{reviewer.full_name} claimed the review",
             reviewer.full_name, ActorType.user, None, None)
        )
    if status in (CaseStatus.completed, CaseStatus.approved, CaseStatus.posting):
        if case.straight_through:
            steps.append(
                (215, "review.skipped", "Confidence above threshold — no human review needed",
                 "review_gate", ActorType.agent, None, None)
            )
        else:
            steps += [
                (900, "review.claimed", f"{reviewer.full_name} claimed the review",
                 reviewer.full_name, ActorType.user, None, None),
                (1500, "review.approve", f"{reviewer.full_name} approved the extraction",
                 reviewer.full_name, ActorType.user, None, None),
            ]
    if status in (CaseStatus.completed, CaseStatus.posting):
        steps.append(
            (1600, "corebanking.posted",
             "Posted to the core banking system (SIMULATED), idempotency key reused safely",
             "core_banking_mcp", ActorType.system, None, 320)
        )
    if status == CaseStatus.completed:
        steps.append(
            (1650, "case.completed", f"{case.reference} completed", "conductor",
             ActorType.system, None, None)
        )
    if status == CaseStatus.rejected:
        steps.append(
            (1500, "review.reject", f"{reviewer.full_name} rejected the documents",
             reviewer.full_name, ActorType.user, None, None)
        )
    if status == CaseStatus.failed:
        steps.append(
            (300, "pipeline.failed",
             "Extraction failed: document unreadable after 2 retries", "worker_extract",
             ActorType.agent, "extract_trade_license@2.1.0", 8800)
        )

    for offset, action, label, actor, actor_type, prompt_version, duration in steps:
        db.add(
            models.Event(
                case_id=case.id,
                actor=actor,
                actor_type=actor_type,
                action=action,
                label=label,
                detail={"thread_id": case.thread_id},
                prompt_version=prompt_version,
                model_version=MODEL_VERSION if actor_type == ActorType.agent else None,
                duration_ms=duration,
                created_at=created_at + timedelta(seconds=offset),
            )
        )


