# --------------------------------------------------------------------------- helpers
def _date(days_from_now: int) -> str:
    return (datetime.now(UTC) + timedelta(days=days_from_now)).date().isoformat()


def _licence_number() -> str:
    return f"CN-{rng.randint(1000000, 9999999)}"


def _emirates_id() -> str:
    return f"784-{rng.randint(1960, 2005)}-{rng.randint(1000000, 9999999)}-{rng.randint(1, 9)}"


def _passport_number() -> str:
    return f"{rng.choice('ABCEKNPRZ')}{rng.randint(1000000, 9999999)}"


def _iban() -> str:
    return "AE" + "".join(str(rng.randint(0, 9)) for _ in range(21))


def _confidence(high: bool) -> float:
    return round(rng.uniform(0.93, 0.995) if high else rng.uniform(0.52, 0.86), 3)


def _calibrate(raw: float) -> float:
    """The model is slightly over-confident; calibration pulls high values down a little."""
    return round(max(0.05, min(0.99, raw - (raw - 0.5) * 0.08)), 3)


# --------------------------------------------------------------------------- users
async def seed_users(db: AsyncSession) -> dict[Role, models.User]:
    password_hash = hash_password(settings.demo_password)
    users: dict[Role, models.User] = {}
    for account in DEMO_ACCOUNTS:
        user = models.User(
            email=account.email,
            full_name=account.full_name,
            full_name_ar=account.full_name_ar,
            role=account.role,
            hashed_password=password_hash,
            is_active=True,
            is_demo=True,
        )
        db.add(user)
        users[account.role] = user
    await db.flush()
    logger.info("seeded %d demo users", len(users))
    return users


# --------------------------------------------------------------------------- config
async def seed_document_types(db: AsyncSession) -> dict[DocTypeKey, models.DocumentType]:
    out: dict[DocTypeKey, models.DocumentType] = {}
    for definition in DOC_TYPE_DEFS:
        rules = [
            {**rule, "severity": Severity(rule["severity"]).value}
            for rule in definition["rules"]  # type: ignore[union-attr]
        ]
        doc_type = models.DocumentType(
            key=definition["key"],
            name_en=definition["name_en"],
            name_ar=definition["name_ar"],
            description=definition["description"],
            version=definition["version"],
            prompt_key=definition["prompt_key"],
            rules_version=definition["rules_version"],
            field_schema=definition["fields"],
            rules=rules,
            is_active=True,
        )
        db.add(doc_type)
        out[definition["key"]] = doc_type  # type: ignore[index]
    await db.flush()
    logger.info("seeded %d document types", len(out))
    return out


async def seed_prompts(db: AsyncSession) -> None:
    for definition in PROMPT_DEFS:
        prompt = models.Prompt(
            key=definition["key"],
            name=definition["name"],
            description=definition["description"],
            document_type=definition["document_type"],
        )
        db.add(prompt)
        await db.flush()
        for index, version in enumerate(definition["versions"]):  # type: ignore[union-attr]
            created = datetime.now(UTC) - timedelta(days=40 - index * 12)
            approved = version.get("approved_by")
            db.add(
                models.PromptVersion(
                    prompt_id=prompt.id,
                    version=version["version"],
                    status=PromptStatus(version["status"]),
                    body=version["body"],
                    notes=version["notes"],
                    eval_score=None,
                    created_by=version.get("created_by", ""),
                    created_at=created,
                    approved_by=approved,
                    approved_at=created + timedelta(hours=6) if approved else None,
                )
            )
    await db.flush()
    logger.info("seeded %d prompts", len(PROMPT_DEFS))


