async def seed_quality(db: AsyncSession) -> None:
    now = datetime.now(UTC)
    for band, (total, failed) in BAND_PLAN.items():
        for run_index in range(3):
            started = now - timedelta(days=run_index * 3, hours=rng.randint(1, 9))
            run_failed = failed if run_index == 0 else failed + rng.randint(0, 3)
            run_passed = total - run_failed
            run = models.QualityRun(
                band=band,
                started_at=started,
                finished_at=started + timedelta(minutes=rng.randint(2, 11)),
                passed=run_passed,
                failed=run_failed,
                score=round(run_passed / total, 4),
                triggered_by="ci" if run_index else "Rashid Belhoul",
                commit_sha=f"{rng.getrandbits(28):07x}",
                created_at=started,
            )
            db.add(run)
            await db.flush()

            if run_index == 0:
                names = BAND_CASE_NAMES[band]
                for case_index, name in enumerate(names):
                    passed = case_index >= run_failed
                    db.add(
                        models.QualityCase(
                            run_id=run.id,
                            name=name,
                            band=band,
                            passed=passed,
                            expected="exact match with the answer key",
                            actual="match" if passed else "value differs from the answer key",
                            note=""
                            if passed
                            else "Added to the regression set from a reviewer correction.",
                            is_regression=not passed,
                        )
                    )
    await db.flush()
    logger.info("seeded quality runs for %d bands", len(BAND_PLAN))


async def seed_calibration(db: AsyncSession) -> None:
    """A slightly over-confident model: stated confidence sits above observed accuracy."""
    for step in range(10):
        predicted = round(0.05 + step * 0.1, 2)
        observed = round(min(0.99, max(0.02, predicted - 0.06 + rng.uniform(-0.03, 0.03))), 3)
        db.add(
            models.CalibrationPoint(
                predicted=predicted,
                observed=observed,
                n=rng.randint(40, 220),
                model_version=MODEL_VERSION,
            )
        )
    await db.flush()


# --------------------------------------------------------------------------- entry point
async def already_seeded(db: AsyncSession) -> bool:
    count = (await db.execute(select(func.count(models.User.id)))).scalar_one()
    return count > 0


# TRUNCATE, not DELETE. Since M4 the `events` table carries a trigger that rejects every
# UPDATE and DELETE, because an audit trail that the application can edit is not an audit trail.
# TRUNCATE does not fire row triggers, and that is the right boundary rather than a loophole:
# it needs table-owner rights and empties the table completely, so it cannot be used to quietly
# alter one record — which is the thing the control exists to prevent. Wiping a demo database is
# a visible, wholesale act; rewriting history is not.
_CLEAR_TABLES = (
    "regression_examples",
    "calibration_experiments",
    "quality_cases",
    "quality_runs",
    "calibration_points",
    "calibration_curves",
    "postings",
    "events",
    "review_tasks",
    "findings",
    "extracted_fields",
    "documents",
    "cases",
    "prompt_versions",
    "prompts",
    "document_types",
    "users",
)


async def clear_all(db: AsyncSession) -> None:
    await db.execute(
        text(f"TRUNCATE TABLE {', '.join(_CLEAR_TABLES)} RESTART IDENTITY CASCADE")
    )
    await db.flush()


async def seed(force: bool = False) -> None:
    async with SessionLocal() as db:
        if await already_seeded(db):
            if not force:
                logger.info("database already seeded — nothing to do")
                return
            logger.warning("force seed: clearing existing data")
            await clear_all(db)

        users = await seed_users(db)
        doc_types = await seed_document_types(db)
        await seed_prompts(db)
        await seed_cases(db, users, doc_types)
        await seed_quality(db)
        await seed_calibration(db)
        await db.commit()
        logger.info("seed complete")


def main() -> None:
    logging.basicConfig(level="INFO", format="%(levelname)s %(name)s | %(message)s")
    import os

    asyncio.run(seed(force=os.environ.get("WATHIQ_FORCE_SEED") == "1"))


if __name__ == "__main__":
    main()
